from __future__ import annotations

import copy
import hashlib
import json
import os
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional

# Single, shared registry file used by every entry point (main.py, run_agent.py,
# run_human.py) so runs across all three can be queried from one place instead of
# inferring grouping from per-run filenames.
DEFAULT_REGISTRY_PATH = Path("checkpoints/artifact_registry.json")


@dataclass
class ExecutionConfig:
    mode: str = "training"
    seed: Optional[int] = None
    deterministic: bool = False
    seed_used: Optional[int] = None
    agent_name: str = ""
    case_id: Optional[str] = None
    run_id: Optional[str] = None
    extra: Dict[str, Any] = field(default_factory=dict)

    @classmethod
    def resolve(cls, mode: str = "training", overrides: Optional[Dict[str, Any]] = None) -> "ExecutionConfig":
        overrides = overrides or {}
        base = {
            "mode": mode,
            "agent_name": overrides.get("agent_name", ""),
            "case_id": overrides.get("case_id"),
            "run_id": overrides.get("run_id"),
            "extra": {},
        }

        if mode in {"testing", "validation", "inference"}:
            base.update({
                "deterministic": True,
                "seed": 0,
                "seed_used": 0,
            })
        else:
            seed_value = overrides.get("seed")
            if seed_value is None:
                # Unpinned training seed: still generate and log one so the run is
                # reproducible later without requiring the user to opt into seeding.
                base.update({
                    "deterministic": bool(overrides.get("deterministic", False)),
                    "seed": None,
                    "seed_used": int.from_bytes(os.urandom(4), "big") % (2 ** 31),
                })
            else:
                base.update({
                    "deterministic": bool(overrides.get("deterministic", False)),
                    "seed": int(seed_value),
                    "seed_used": int(seed_value),
                })

        base.update({k: v for k, v in overrides.items() if k not in {"seed", "deterministic", "mode", "agent_name", "case_id", "run_id"}})
        if "extra" in base:
            extra = base.get("extra") or {}
            base["extra"] = dict(extra)

        return cls(**base)

    def to_dict(self) -> Dict[str, Any]:
        payload = {
            "mode": self.mode,
            "seed": self.seed,
            "deterministic": self.deterministic,
            "seed_used": self.seed_used,
            "agent_name": self.agent_name,
            "case_id": self.case_id,
            "run_id": self.run_id,
            "extra": copy.deepcopy(self.extra),
        }
        return payload

    def config_hash(self) -> str:
        encoded = json.dumps(self.to_dict(), sort_keys=True, separators=(",", ":"), default=str)
        return hashlib.sha256(encoded.encode("utf-8")).hexdigest()[:12]

    def apply_seed(self) -> None:
        """Seed stdlib random and (if installed) numpy with `seed_used`, so an
        unpinned seed generated by `resolve` is actually the seed in effect."""
        if self.seed_used is None:
            return
        import random as _random
        _random.seed(self.seed_used)
        try:
            import numpy as _np
            _np.random.seed(self.seed_used)
        except ImportError:
            pass

    def scoped_view(self) -> "ScopedExecutionConfig":
        """Return a read-only, mode-scoped view exposing only the fields relevant
        to `self.mode`, so agent code can't reach into fields of other modes
        (e.g. training's mutable `extra` hyperparameters from an inference run)."""
        allowed = _MODE_FIELD_OVERLAYS.get(self.mode, _MODE_FIELD_OVERLAYS["training"])
        full = self.to_dict()
        values = {name: full[name] for name in allowed if name in full}
        return ScopedExecutionConfig(self.mode, values)


# Single base schema (ExecutionConfig above) with per-mode overlays declaring which
# fields are exposed to agent code via `scoped_view()`. Add new modes/fields here only.
_MODE_FIELD_OVERLAYS: Dict[str, tuple] = {
    "training": ("mode", "seed_used", "agent_name", "case_id", "run_id", "extra"),
    "testing": ("mode", "seed_used", "deterministic", "agent_name", "case_id", "run_id"),
    "validation": ("mode", "seed_used", "deterministic", "agent_name", "case_id", "run_id"),
    "inference": ("mode", "seed_used", "deterministic", "agent_name", "case_id", "run_id"),
}


class ScopedExecutionConfig:
    """Read-only, mode-scoped facade over `ExecutionConfig`. Only fields declared in
    `_MODE_FIELD_OVERLAYS[mode]` are accessible; anything else raises AttributeError."""

    __slots__ = ("_mode", "_values")

    def __init__(self, mode: str, values: Dict[str, Any]) -> None:
        object.__setattr__(self, "_mode", mode)
        object.__setattr__(self, "_values", values)

    def __getattr__(self, name: str) -> Any:
        values = object.__getattribute__(self, "_values")
        if name not in values:
            mode = object.__getattribute__(self, "_mode")
            raise AttributeError(f"{name!r} is not exposed to {mode!r} mode config")
        return values[name]

    def __setattr__(self, name: str, value: Any) -> None:
        raise AttributeError("ScopedExecutionConfig is read-only")

    def __repr__(self) -> str:
        return f"ScopedExecutionConfig(mode={self._mode!r}, fields={sorted(self._values)})"


class ArtifactRegistry:
    def __init__(self, path: Path | str) -> None:
        self.path = Path(path)
        self.path.parent.mkdir(parents=True, exist_ok=True)
        if self.path.exists():
            self._data = json.loads(self.path.read_text(encoding="utf-8"))
        else:
            self._data = {"schema_version": 1, "entries": []}

    def _persist(self) -> None:
        tmp_path = f"{self.path}.tmp"
        with open(tmp_path, "w", encoding="utf-8") as handle:
            json.dump(self._data, handle, indent=2)
        if self.path.exists():
            self.path.unlink()
        os.replace(tmp_path, self.path)

    def register(
        self,
        *,
        artifact_kind: str,
        artifact_path: str,
        case_id: Optional[str] = None,
        run_id: Optional[str] = None,
        agent_name: str,
        mode: str,
        metrics: Optional[Dict[str, Any]] = None,
        parent_checkpoint_id: Optional[str] = None,
        config_hash: Optional[str] = None,
    ) -> Dict[str, Any]:
        entry = {
            "id": f"{agent_name}:{run_id or 'unknown'}:{artifact_kind}",
            "artifact_kind": artifact_kind,
            "artifact_path": artifact_path,
            "case_id": case_id,
            "run_id": run_id,
            "agent_name": agent_name,
            "mode": mode,
            "metrics": metrics or {},
            "parent_checkpoint_id": parent_checkpoint_id,
            "config_hash": config_hash,
            "updated_at": datetime.now(timezone.utc).isoformat(),
        }
        self._data.setdefault("entries", []).append(entry)
        self._persist()
        return entry

    def record_run_start(
        self,
        *,
        agent_name: str,
        mode: str,
        run_id: Optional[str] = None,
        case_id: Optional[str] = None,
        config_hash: Optional[str] = None,
        metadata: Optional[Dict[str, Any]] = None,
    ) -> Dict[str, Any]:
        """Register the start of a single execution. Every artifact produced by this
        execution should be registered afterwards with the same run_id."""
        return self.register(
            artifact_kind="run_start",
            artifact_path="",
            case_id=case_id,
            run_id=run_id,
            agent_name=agent_name,
            mode=mode,
            metrics=metadata or {},
            config_hash=config_hash,
        )

    def record_run_complete(
        self,
        *,
        agent_name: str,
        mode: str,
        run_id: Optional[str] = None,
        case_id: Optional[str] = None,
        config_hash: Optional[str] = None,
        metrics: Optional[Dict[str, Any]] = None,
    ) -> Dict[str, Any]:
        """Register the completion of a single execution, with summary metrics."""
        return self.register(
            artifact_kind="run_complete",
            artifact_path="",
            case_id=case_id,
            run_id=run_id,
            agent_name=agent_name,
            mode=mode,
            metrics=metrics or {},
            config_hash=config_hash,
        )

    def query(
        self,
        *,
        case_id: Optional[str] = None,
        run_id: Optional[str] = None,
        agent_name: Optional[str] = None,
        artifact_kind: Optional[str] = None,
    ) -> List[Dict[str, Any]]:
        """Return every entry matching all of the supplied identifiers.

        This is the primary lookup used by reporting/A-B tooling: query by
        case_id to compare runs, by run_id to resolve everything one execution
        produced, or by agent_name to find an agent's history across runs.
        """
        matches = []
        for entry in self._data.get("entries", []):
            if case_id is not None and entry.get("case_id") != case_id:
                continue
            if run_id is not None and entry.get("run_id") != run_id:
                continue
            if agent_name is not None and entry.get("agent_name") != agent_name:
                continue
            if artifact_kind is not None and entry.get("artifact_kind") != artifact_kind:
                continue
            matches.append(entry)
        return matches

    def lookup(self, *, case_id: Optional[str] = None, run_id: Optional[str] = None, agent_name: Optional[str] = None) -> Optional[Dict[str, Any]]:
        """Return the first entry matching the given identifiers. Prefer `query`
        when more than one match is expected (e.g. multiple artifacts per run)."""
        matches = self.query(case_id=case_id, run_id=run_id, agent_name=agent_name)
        return matches[0] if matches else None

    def get_by_id(self, entry_id: str) -> Optional[Dict[str, Any]]:
        """Look up a single entry by its canonical `id` (linear scan of `entries`)."""
        for entry in self._data.get("entries", []):
            if entry.get("id") == entry_id:
                return entry
        return None


class CheckpointManager:
    """Resolves per-`agent_name` checkpoint file paths (one untagged `latest`
    lineage plus a separate lineage per `case_id`) and records lineage/parentage
    in the `ArtifactRegistry`. Actual file writes are delegated to the agent's
    own atomic `save()`; this class only decides *where* to write and chains
    `parent_checkpoint_id` within a lineage."""

    def __init__(self, registry: ArtifactRegistry, root: Path | str = Path("checkpoints")) -> None:
        self.registry = registry
        self.root = Path(root)

    @staticmethod
    def _lineage(case_id: Optional[str]) -> str:
        return f"case-{case_id}" if case_id else "latest"

    def checkpoint_path(self, agent_name: str, case_id: Optional[str] = None) -> Path:
        return self.root / (agent_name or "unknown") / f"{self._lineage(case_id)}.pt"

    def resolve_resume_path(self, agent_name: str, case_id: Optional[str] = None) -> Optional[str]:
        """Path new training should resume from: the case-tagged lineage when
        `case_id` is given, otherwise the untagged `latest` lineage."""
        path = self.checkpoint_path(agent_name, case_id)
        return str(path) if path.exists() else None

    def list_checkpoints(self, agent_name: str, case_id: Optional[str] = None) -> List[Dict[str, Any]]:
        """Independently list one lineage: case-tagged entries when `case_id`
        is given, otherwise only the untagged `latest` lineage."""
        matches = self.registry.query(agent_name=agent_name, artifact_kind="checkpoint")
        if case_id is not None:
            return [m for m in matches if m.get("case_id") == case_id]
        return [m for m in matches if m.get("case_id") is None]

    def latest_entry(self, agent_name: str, case_id: Optional[str] = None) -> Optional[Dict[str, Any]]:
        entries = self.list_checkpoints(agent_name, case_id)
        return entries[-1] if entries else None

    def checkpoint_metadata(self, checkpoint_id: str) -> Optional[Dict[str, Any]]:
        """Read path for a given checkpoint_id: returns its `parent_checkpoint_id`,
        `case_id`, and `config_hash` from the registry. No filename parsing —
        this is a registry lookup by `id` only."""
        entry = self.registry.get_by_id(checkpoint_id)
        if entry is None:
            return None
        return {
            "parent_checkpoint_id": entry.get("parent_checkpoint_id"),
            "case_id": entry.get("case_id"),
            "config_hash": entry.get("config_hash"),
        }

    def save(
        self,
        agent: Any,
        *,
        agent_name: str,
        case_id: Optional[str],
        run_id: Optional[str],
        mode: str,
        config_hash: str,
        metrics: Optional[Dict[str, Any]] = None,
    ) -> Dict[str, Any]:
        """Save `agent` to its lineage's checkpoint path and register it with
        `parent_checkpoint_id` pointing at the previous entry in that same
        lineage, so lineage history is chainable and unambiguous."""
        path = self.checkpoint_path(agent_name, case_id)
        path.parent.mkdir(parents=True, exist_ok=True)
        parent = self.latest_entry(agent_name, case_id)
        parent_id = parent["id"] if parent else None
        agent.save(str(path))
        return self.registry.register(
            artifact_kind="checkpoint",
            artifact_path=str(path),
            case_id=case_id,
            run_id=run_id,
            agent_name=agent_name,
            mode=mode,
            metrics=metrics or {},
            parent_checkpoint_id=parent_id,
            config_hash=config_hash,
        )


class HistoryManager:
    """Resolves per-`agent_name` training-history file paths using the same
    lineage scheme as `CheckpointManager` (untagged `latest` vs a lineage per
    `case_id`), so history and checkpoints share identifiers and can be joined
    by `run_id`/`agent_name`/`case_id` alone, with no filename parsing."""

    def __init__(self, registry: ArtifactRegistry, root: Path | str = Path("history")) -> None:
        self.registry = registry
        self.root = Path(root)

    @staticmethod
    def _lineage(case_id: Optional[str]) -> str:
        return f"case-{case_id}" if case_id else "latest"

    def history_path(self, agent_name: str, case_id: Optional[str] = None) -> Path:
        return self.root / (agent_name or "unknown") / f"{self._lineage(case_id)}.json"

    def list_history(self, agent_name: str, case_id: Optional[str] = None) -> List[Dict[str, Any]]:
        """Independently list one lineage's history entries: case-tagged when
        `case_id` is given, otherwise only the untagged `latest` lineage."""
        matches = self.registry.query(agent_name=agent_name, artifact_kind="history")
        if case_id is not None:
            return [m for m in matches if m.get("case_id") == case_id]
        return [m for m in matches if m.get("case_id") is None]

    def record(
        self,
        *,
        agent_name: str,
        case_id: Optional[str],
        run_id: Optional[str],
        mode: str,
        config_hash: Optional[str] = None,
        metrics: Optional[Dict[str, Any]] = None,
    ) -> Dict[str, Any]:
        """Register a history write against this lineage's path. Callers still
        do the actual file write (via `TrainingHistory.save`) to `history_path`."""
        path = self.history_path(agent_name, case_id)
        return self.registry.register(
            artifact_kind="history",
            artifact_path=str(path),
            case_id=case_id,
            run_id=run_id,
            agent_name=agent_name,
            mode=mode,
            metrics=metrics or {},
            config_hash=config_hash,
        )
