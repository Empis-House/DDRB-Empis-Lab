from __future__ import annotations

import ast
from typing import Iterable, List, Sequence

import numpy as np


def normalize_level_tokens(level: object) -> List[int]:
    """Normalize a level representation into a list of integer tokens.

    Supported inputs:
    - list/tuple/np.ndarray/pandas Series of ints or numeric strings
    - string representation like "[1, 2, 3]"
    - compact numeric strings like "123" are treated as per-character tokens
    """
    if level is None:
        return []

    if isinstance(level, str):
        raw = level.strip()
        if not raw:
            return []

        # Handle repr-style sequences generated by older code paths.
        if raw.startswith("[") and raw.endswith("]"):
            try:
                parsed = ast.literal_eval(raw)
                if isinstance(parsed, (list, tuple, np.ndarray)):
                    return [int(x) for x in parsed]
            except (ValueError, SyntaxError):
                pass

        # Fallback for compact strings like "0123".
        return [int(ch) for ch in raw if ch.isdigit()]

    if isinstance(level, np.ndarray):
        return [int(x) for x in level.tolist()]

    if isinstance(level, (list, tuple)):
        return [int(x) for x in level]

    if hasattr(level, "tolist"):
        values = level.tolist()
        if isinstance(values, list):
            return [int(x) for x in values]

    return []


def build_metric_lookup(df, metric_name: str) -> dict[int, float]:
    if df is None:
        raise ValueError("df is required for evaluation")
    if "token" not in df.columns:
        raise KeyError("df must include 'token' column")
    if metric_name not in df.columns:
        raise KeyError(f"df must include '{metric_name}' column")

    token_series = df["token"].astype(int)
    metric_series = df[metric_name].astype(float)
    return dict(zip(token_series.tolist(), metric_series.tolist()))


def metric_values(level: object, df, metric_name: str) -> List[float]:
    tokens = normalize_level_tokens(level)
    if not tokens:
        return []

    lookup = build_metric_lookup(df, metric_name)
    return [lookup[token] for token in tokens if token in lookup]


def normalized_mean(values: Sequence[float]) -> float:
    if not values:
        return 0.0
    max_value = max(values)
    if max_value <= 0:
        return 0.0
    return float(sum(values) / (max_value * len(values)))
